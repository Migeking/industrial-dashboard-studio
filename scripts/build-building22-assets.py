"""Build the offline BAS-22 asset bundle from pinned Three.js and CC0 assets."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import base64
import hashlib
import json
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'works/scene22/sources'
OUTPUT = ROOT / 'assets/models/building22'
CACHE.mkdir(parents=True, exist_ok=True)
OUTPUT.mkdir(parents=True, exist_ok=True)
records = {}


def download(url):
    path = CACHE / (hashlib.sha256(url.encode()).hexdigest()[:16] + '-' + url.rsplit('/', 1)[-1])
    if not path.exists():
        for attempt in range(3):
            try:
                request = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (BAS22 offline asset builder)'})
                with urllib.request.urlopen(request, timeout=35) as response:
                    data = response.read()
                path.write_bytes(data)
                break
            except Exception:
                if attempt == 2:
                    raise
                time.sleep(1)
    data = path.read_bytes()
    records[url] = {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
    return data


def data_uri(data, mime):
    return 'data:' + mime + ';base64,' + base64.b64encode(data).decode()


def asset_files(asset):
    return json.loads(download('https://api.polyhaven.com/files/' + asset))


def model(asset):
    entry = asset_files(asset)['gltf']['1k']['gltf']
    document = json.loads(download(entry['url']))
    includes = entry['include']
    resources = {uri: content for uri, content in zip(includes, pool.map(download, [item['url'] for item in includes.values()]))}
    for buffer in document.get('buffers', []):
        buffer['uri'] = data_uri(resources[buffer['uri']], 'application/octet-stream')
    for image in document.get('images', []):
        uri = image['uri']
        image['uri'] = data_uri(resources[uri], 'image/png' if uri.endswith('.png') else 'image/jpeg')
    print('Packed model:', asset, flush=True)
    return document


def surface(asset):
    files = asset_files(asset)
    result = {}
    for name, candidates in [('diff', ['Diffuse', 'diff']), ('normal', ['nor_gl']), ('rough', ['Rough', 'rough'])]:
        key = next(key for key in candidates if key in files)
        entry = files[key]['1k']['jpg']
        result[name] = data_uri(download(entry['url']), 'image/jpeg')
    print('Packed material:', asset, flush=True)
    return result


with ThreadPoolExecutor(max_workers=5) as pool:
    payload = {
        'models': {asset: model(asset) for asset in ['modern_arm_chair_01', 'potted_plant_04']},
        'surfaces': {asset: surface(asset) for asset in ['rosewood_veneer_02', 'dirty_carpet', 'terrazzo_tiles']},
        'environment': base64.b64encode(download('https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/1k/lebombo_1k.hdr')).decode(),
    }
    sources = []
    for filename in ['loaders/GLTFLoader.js', 'loaders/RGBELoader.js', 'math/SimplexNoise.js',
                     'shaders/CopyShader.js', 'shaders/SSAOShader.js', 'shaders/FXAAShader.js',
                     'postprocessing/Pass.js', 'postprocessing/SSAOPass.js']:
        url = 'https://raw.githubusercontent.com/mrdoob/three.js/r128/examples/js/' + filename
        sources.append(download(url).decode())
    bundle = '// Generated by scripts/build-building22-assets.py. Three.js: MIT; Poly Haven assets: CC0.\n'
    bundle += (ROOT / 'vendor/OrbitControls.js').read_text(encoding='utf-8') + '\n'
    bundle += '\n'.join(sources)
    bundle += '\nwindow.Building22Assets = ' + json.dumps(payload, separators=(',', ':')) + ';\n'
    (OUTPUT / 'building22-assets.js').write_text(bundle, encoding='utf-8', newline='\n')
    license_url = 'https://raw.githubusercontent.com/mrdoob/three.js/r128/LICENSE'
    (OUTPUT / 'THREE-LICENSE.txt').write_bytes(download(license_url))
    manifest = {
        'license': 'https://polyhaven.com/license',
        'three_version': 'r128',
        'assets': ['https://polyhaven.com/a/' + asset for asset in [*payload['models'], *payload['surfaces'], 'lebombo']],
        'files': dict(sorted(records.items())),
        'bundle_sha256': hashlib.sha256(bundle.encode()).hexdigest(),
    }
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print('Bundle bytes:', len(bundle.encode()), flush=True)
