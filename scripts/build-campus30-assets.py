"""Bundle pinned Three.js postprocessing and CC0 campus surface assets for file:// use."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import base64
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'works/scene30/sources'
OUT = ROOT / 'assets/models/campus30'
CACHE.mkdir(parents=True, exist_ok=True)
records = {}

def download(url):
    name = hashlib.sha256(url.encode()).hexdigest()[:16] + '-' + url.rsplit('/', 1)[-1]
    path = CACHE / name
    old_cache = ROOT / 'works/scene22/sources' / name
    if not path.exists():
        if old_cache.exists():
            path.write_bytes(old_cache.read_bytes())
        else:
            request = urllib.request.Request(url, headers={'User-Agent': 'Campus30 offline asset builder'})
            with urllib.request.urlopen(request, timeout=60) as response:
                path.write_bytes(response.read())
    data = path.read_bytes()
    records[url] = {'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}
    return data

def uri(data, mime='image/jpeg'):
    return 'data:' + mime + ';base64,' + base64.b64encode(data).decode()

def surface(asset):
    files = json.loads(download('https://api.polyhaven.com/files/' + asset))
    maps = {}
    for role, candidates in [('diff', ['Diffuse', 'diff']), ('normal', ['nor_gl']), ('rough', ['Rough', 'rough'])]:
        key = next(k for k in candidates if k in files)
        maps[role] = uri(download(files[key]['1k']['jpg']['url']))
    print('Packed:', asset, flush=True)
    return asset, maps

with ThreadPoolExecutor(max_workers=4) as pool:
    surfaces = dict(pool.map(surface, ['asphalt_02', 'concrete_floor_painted', 'aerial_grass_rock']))
    hdr_files = json.loads(download('https://api.polyhaven.com/files/kloppenheim_06_puresky'))
    hdr = download(hdr_files['hdri']['1k']['hdr']['url'])
    deps = []
    for file in ['loaders/RGBELoader.js', 'math/SimplexNoise.js', 'shaders/CopyShader.js',
                 'shaders/SSAOShader.js', 'shaders/FXAAShader.js', 'postprocessing/Pass.js', 'postprocessing/SSAOPass.js']:
        deps.append(download('https://raw.githubusercontent.com/mrdoob/three.js/r128/examples/js/' + file).decode())
    payload = {'surfaces': surfaces, 'environment': base64.b64encode(hdr).decode()}
    bundle = '// Generated by scripts/build-campus30-assets.py; Three.js MIT; Poly Haven CC0.\n'
    bundle += '\n'.join(deps)
    bundle += '\nwindow.Campus30Assets = ' + json.dumps(payload, separators=(',', ':')) + ';\n'
    bundle += (OUT / 'campus30-scene.js').read_text(encoding='utf-8')
    (OUT / 'campus30-assets.js').write_text(bundle, encoding='utf-8', newline='\n')
    (OUT / 'THREE-LICENSE.txt').write_bytes(download('https://raw.githubusercontent.com/mrdoob/three.js/r128/LICENSE'))
    manifest = {
        'three_version': 'r128', 'license': 'https://polyhaven.com/license',
        'assets': ['https://polyhaven.com/a/' + asset for asset in [*surfaces, 'kloppenheim_06_puresky']],
        'files': dict(sorted(records.items())),
        'source_sha256': hashlib.sha256((OUT / 'campus30-scene.js').read_bytes()).hexdigest(),
        'bundle_sha256': hashlib.sha256((OUT / 'campus30-assets.js').read_bytes()).hexdigest()
    }
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8', newline='\n')
    print('Bundle bytes:', len(bundle.encode()), flush=True)
