"""Package selected transparent equipment artwork; resize/encode only, no visual retouching.

Import: python -X utf8 scripts/build-water-artwork.py --import-manifest works/water-component-artwork/generation-final.json
Rebuild embedded offline module: python -X utf8 scripts/build-water-artwork.py
"""
import argparse
import base64
import hashlib
import json
import shutil
import subprocess
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'packages/components/studio/assets/water'
MODULE=ROOT/'packages/components/studio/water-artwork.mjs'

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--import-manifest',type=Path)
    args=parser.parse_args()
    ids=json.loads(subprocess.check_output(['node','--input-type=module','-e',
        'import {waterEquipment} from "./packages/components/studio/water-equipment.mjs";console.log(JSON.stringify(Object.keys(waterEquipment)))'],cwd=ROOT))
    ASSETS.mkdir(parents=True,exist_ok=True)
    if args.import_manifest:
        chosen=json.loads(args.import_manifest.read_text('utf-8'))
        assert len({a['id'] for a in chosen})==len(chosen) and {a['id'] for a in chosen}<=set(ids),'Manifest has duplicate or unknown components'
        existing=json.loads((ASSETS/'provenance.json').read_text('utf-8'))['assets'] if (ASSETS/'provenance.json').exists() else []
        provenance=[a for a in existing if a['id'] not in {c['id'] for c in chosen}]
        for asset in chosen:
            key=asset['id'];source=Path(asset['source']);im=Image.open(source).convert('RGBA')
            alpha=im.getchannel('A')
            assert all(alpha.getpixel(p)<=3 for p in [(0,0),(im.width-1,0),(0,im.height-1),(im.width-1,im.height-1)]),f'{key}: non-transparent corners'
            assert alpha.histogram()[0]/(im.width*im.height)>.05,f'{key}: background is not transparent'
            selected=ROOT/'works/water-component-artwork/selected'/f'{key}.png'
            selected.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(source,selected)
            im.thumbnail((1024,768),Image.Resampling.LANCZOS)
            target=ASSETS/f'{key}.webp';im.save(target,'WEBP',quality=92,method=6,exact=True)
            provenance.append({'id':key,'file':target.name,'size':list(im.size),'bytes':target.stat().st_size,
                'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'prompt':asset['prompt'],'edits':asset.get('edits',[])})
        (ASSETS/'provenance.json').write_text(json.dumps({'tool':'built-in image_gen','assets':provenance},ensure_ascii=False,indent=2)+'\n','utf-8')
    artwork={}
    for key in ids:
        data=(ASSETS/f'{key}.webp').read_bytes()
        artwork[key]='data:image/webp;base64,'+base64.b64encode(data).decode('ascii')
    MODULE.write_text('// Generated by scripts/build-water-artwork.py. Transparent equipment artwork embedded for offline delivery.\nexport const waterArtwork = '+json.dumps(artwork,separators=(',',':'))+';\n','utf-8')
    print(f'Packaged {len(artwork)} assets; embedded module {MODULE.stat().st_size:,} bytes')

if __name__=='__main__':main()
